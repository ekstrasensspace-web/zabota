def process_getcourse_message(payload):
    # Игнорируем сообщения от ботов (например mac_academy_bot шлёт воронку)
    try:
        def _find_bot_sender(obj, depth=0):
            """Рекурсивно ищет from.is_bot=True в любом месте payload."""
            if depth > 6 or not isinstance(obj, dict):
                return None
            f = obj.get("from")
            if isinstance(f, dict) and f.get("is_bot"):
                return f.get("username", "unknown_bot")
            for v in obj.values():
                if isinstance(v, dict):
                    result = _find_bot_sender(v, depth + 1)
                    if result:
                        return result
            return None

        bot_sender = _find_bot_sender(payload)
        if bot_sender:
            print(f"GetCourse bot-message ignored (from bot: {bot_sender})", flush=True)
            return None
    except Exception:
        pass

    client_id, user_message, user_name, event_id = extract_getcourse_payload(payload)

    if not client_id or not user_message:
        print(f"GetCourse webhook ignored: no client_id/message. Payload={payload}", flush=True)
        return None
    if event_id:
        event_key = str(event_id)
        if event_key in processed_getcourse_events:
            print(f"GetCourse duplicate ignored: {event_key}", flush=True)
            return None
        processed_getcourse_events.add(event_key)
        if len(processed_getcourse_events) > 1000:
            processed_getcourse_events.clear()
    if is_salebot_noise_message(user_message):
        print(f"GetCourse noise ignored for client {client_id}: {user_message[:120]}", flush=True)
        return None
    if is_passive_funnel_message(user_message):
        print(f"GetCourse funnel/passive ignored for client {client_id}: {user_message[:120]}", flush=True)
        return None
    now = time.time()
    last_answer_at = getcourse_last_answer.get(client_id, 0)
    if now - last_answer_at < 12:
        print(f"GetCourse rate-limit ignored for client {client_id}: {user_message[:120]}", flush=True)
        return None
    getcourse_last_answer[client_id] = now

    user_key = f"getcourse:{client_id}"
    if looks_like_symbol_decode_request(user_message):
        reply = generate_symbol_decode_reply(user_message, language="ru")
    else:
        reply = predefined_reply_for_message(user_message) or generate_ai_reply(user_key, user_message)
    used_fallback = False
    if not reply:
        reply = fallback_reply_for_message(user_message)
        used_fallback = True
    reason = human_attention_reason(user_message, reply)
    if used_fallback and not reason:
        reason = "AI не ответил, клиенту отправлен резервный ответ"
    if reason:
        telegram_notify_sync(build_human_attention_notice(
            "GetCourse/VK",
            user_name,
            client_id,
            user_message,
            reply,
            reason,
            "Тейковер: откройте клиента в GetCourse/VK и возьмите диалог вручную.",
        ))
    else:
        telegram_notify_sync(
            f"👤 GetCourse/VK — {user_name} ({client_id}):\n{user_message}\n\n"
            f"🤖 Бот:\n{reply}"
        )
    print(f"GetCourse reply generated for {client_id}", flush=True)
    return reply

