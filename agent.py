async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.message.from_user.id
    user_message = update.message.text
    user_name = update.message.from_user.first_name or str(user_id)

    # ── Сообщения от администратора ──────────────────────────────────────────
    if user_id in ADMIN_IDS:
        # /takeover USER_ID — взять диалог вручную
        if user_message.startswith("/takeover"):
            parts = user_message.split()
            if len(parts) > 1:
                tid = int(parts[1])
                paused_users.add(tid)
                await update.message.reply_text(f"✅ Взяла управление для {tid}. Бот молчит.")
            return
        # /release USER_ID — вернуть боту
        if user_message.startswith("/release"):
            parts = user_message.split()
            if len(parts) > 1:
                tid = int(parts[1])
                paused_users.discard(tid)
                await update.message.reply_text(f"✅ Бот снова отвечает пользователю {tid}.")
            return
        # /takeover_sb CLIENT_ID — взять VK-диалог вручную
        if user_message.startswith("/takeover_sb"):
            parts = user_message.split()
            if len(parts) > 1:
                cid = parts[1]
                paused_salebot_clients.add(str(cid))
                cancel_salebot_followup(cid)
                await update.message.reply_text(f"✅ Диалог {cid} забран. Бот молчит — вы отвечаете в SaleBot.")
            return
        # /release_sb CLIENT_ID — вернуть VK-диалог боту
        if user_message.startswith("/release_sb"):
            parts = user_message.split()
            if len(parts) > 1:
                cid = parts[1]
                paused_salebot_clients.discard(str(cid))
                await update.message.reply_text(f"✅ Бот снова отвечает клиенту {cid}.")
            return
        # /stats — сколько всего уникальных пользователей
        if user_message.startswith("/stats"):
            total = len(known_users)
            active = len(conversation_history)
            manual = len(paused_users)
            await update.message.reply_text(
                f"📊 Статистика бота:\n\n"
                f"👥 Всего уникальных пользователей: {total}\n"
                f"💬 Активных диалогов сейчас: {active}\n"
                f"🤝 На ручном управлении: {manual}\n\n"
                f"🤖 AI сегодня ({_ai_stats.get('date','—')}):\n"
                f"  ✅ Groq: {_ai_stats.get('groq',0)} вызовов (бесплатно)\n"
                f"  🔁 Gemini: {_ai_stats.get('gemini',0)} вызовов (бесплатно)\n"
                f"  ⚠️ Claude: {_ai_stats.get('claude',0)}/{CLAUDE_DAILY_LIMIT} вызовов (платно!)\n"
                f"  ❌ Нет ответа: {_ai_stats.get('failed',0)}"
            )
            return

        # /list — показать кто на ручном управлении
        if user_message.startswith("/list"):
            if paused_users:
                await update.message.reply_text("На ручном управлении: " + ", ".join(str(x) for x in paused_users))
            else:
                await update.message.reply_text("Все диалоги ведёт бот.")
            return
        # Ответ на пересланное сообщение → отправить клиенту
        if update.message.reply_to_message:
            orig_id = update.message.reply_to_message.message_id
            # Ответ на Telegram-диалог
            if orig_id in forwarded_map:
                client_id = forwarded_map[orig_id]
                await context.bot.send_message(chat_id=client_id, text=user_message)
                await update.message.reply_text(f"✅ Отправлено Telegram-клиенту {client_id}.")
                return
            # Ответ на SaleBot/VK уведомление из зеркала
            if orig_id in salebot_mirror_map:
                sb_client_id, sb_name = salebot_mirror_map[orig_id]
                try:
                    send_salebot_message(sb_client_id, user_message)
                    log_dialog("SaleBot", sb_client_id, sb_name, "[оператор]", user_message)
                    await update.message.reply_text(f"✅ Отправлено в VK клиенту {sb_name} ({sb_client_id}).")
                except Exception as e:
                    await update.message.reply_text(f"❌ Ошибка отправки: {e}")
                return
        return  # прочие сообщения от админа игнорируем

    # ── Сообщения от клиентов ─────────────────────────────────────────────────
    # Фиксируем нового пользователя
    user_id_str = str(user_id)
    if user_id_str not in known_users:
        known_users.add(user_id_str)
        save_user(user_id)

    # Если диалог на ручном управлении — только пересылаем админу
    if user_id in paused_users:
        await notify_admin(context, user_id, user_name, user_message, bot_reply=None)
        return

    # Обычный режим — отвечает бот
    # Сначала проверяем на расшифровку символов (цвет + цифра + символ)
    if looks_like_symbol_decode_request(user_message):
        reply = generate_symbol_decode_reply(user_message, language="ru")
    else:
        reply = predefined_reply_for_message(user_message) or generate_ai_reply(user_id, user_message)
    if not reply:
        reply = fallback_reply_for_message(user_message)
    await reply_text_chunks(update.message, reply)
    log_dialog("Telegram", user_id, user_name, user_message, reply)
    attention_reason = human_attention_reason(user_message, reply)

    # Пересылаем диалог администратору
    try:
        await notify_admin(context, user_id, user_name, user_message, bot_reply=reply, attention_reason=attention_reason)
    except Exception:
        pass  # не ломаем бота если уведомление не дошло

