def recursive_find(data, *keys):
    """Ищем значение в неизвестной структуре webhook payload."""
    if isinstance(data, dict):
        for key in keys:
            value = data.get(key)
            if value is not None and value != "":
                return value
        for value in data.values():
            found = recursive_find(value, *keys)
            if found is not None and found != "":
                return found
    elif isinstance(data, list):
        for item in data:
            found = recursive_find(item, *keys)
            if found is not None and found != "":
                return found
    return None

def is_salebot_form_submission(payload):
    """Анкета/заявка GetCourse — не вопрос клиента, не отвечаем.

    ВАЖНО: проверяем только ТЕКУЩЕЕ событие (верхний уровень payload),
    НЕ сохранённые переменные клиента. У клиента может быть link_anketa /
    proxy_id в профиле от прошлых покупок — это не значит что его текущее
    сообщение "Как купить курс" является анкетой.
    """
    if not isinstance(payload, dict):
        return False

    # result=True/1 на верхнем уровне — итог отправки формы
    result_val = payload.get("result")
    if result_val in (True, 1, "True", "true", "1"):
        return True

    # event_type указывает на сделку/оплату
    event_type = str(payload.get("event_type") or "").lower()
    if any(word in event_type for word in ("deal", "order", "payment", "purchase", "lead")):
        return True

    return False

def is_salebot_comment_payload(payload, message):
    """SaleBot может присылать комментарии как webhook, но ИИ должен отвечать только в личных сообщениях."""
    normalized = message.lower()
    if any(marker in normalized for marker in (
        "fb_client_wall_reply_new_comment",
        "new_comment",
        "reply_new_comment",
        "ответить на комментарий",
    )):
        return True

    client_data = payload.get("client") if isinstance(payload.get("client"), dict) else {}
    variables = client_data.get("variables") if isinstance(client_data.get("variables"), dict) else {}
    order_variables = client_data.get("order_variables") if isinstance(client_data.get("order_variables"), dict) else {}
    comment_markers = (
        "comment_id",
        "facebook_last_comment_id",
        "facebook_media_url",
        "fb_client_wall_reply",
        "private_reply",
    )
    for source in (payload, client_data, variables, order_variables):
        if not isinstance(source, dict):
            continue
        keys_text = " ".join(str(key).lower() for key in source.keys())
        if any(marker in keys_text for marker in comment_markers):
            return True
    return False

def extract_salebot_payload(raw_payload):
    """SaleBot может прислать разные имена полей — вытаскиваем максимально гибко."""
    payload = raw_payload if isinstance(raw_payload, dict) else {}
    client_data = payload.get("client") if isinstance(payload.get("client"), dict) else {}
    message = salebot_value(payload, "message", "text", "callback_message", "msg", "body")
    # В вебхуке SaleBot верхний id часто является id сообщения, а настоящий id клиента лежит в client.id.
    client_id = (
        salebot_value(client_data, "id", "client_id")
        or salebot_value(payload, "client_id", "user_id", "platform_id")
        or salebot_value(payload, "id")
    )
    user_name = (
        salebot_value(client_data, "name", "first_name", "username")
        or salebot_value(payload, "name", "first_name", "client_name", "username")
        or f"SaleBot {client_id}"
    )
    return str(client_id) if client_id is not None else None, str(message).strip() if message else "", str(user_name)

